/**
 * Dennis AI engine helpers — dependency-free building blocks for the Dennis
 * Quality Assistant: document chunking, PII redaction, vector maths, and the
 * provider abstraction (local Ollama + optional online Anthropic/OpenAI/custom).
 *
 * Design constraints (offline-first desktop/LAN app):
 *  - No heavy/native dependencies. Providers are reached over HTTP with the
 *    built-in fetch, so the app installs and runs even when no model is present.
 *  - Every provider call is best-effort and times out; callers must degrade to
 *    document search (extractive answers) when a provider is unavailable.
 */

